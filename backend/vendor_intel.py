def vendors_compare(
    db: Session,
    keys: List[str],
    house: Optional[str] = None,
) -> Dict[str, Any]:
    cleaned: List[str] = []
    for raw in keys:
        key = str(raw or "").strip().lower()
        if key and key not in cleaned:
            cleaned.append(key)
    if not cleaned:
        raise HTTPException(status_code=400, detail="Provide at least one vendor key (?keys=...)")
    if len(cleaned) > MAX_COMPARE_VENDORS:
        raise HTTPException(
            status_code=400,
            detail=f"Compare at most {MAX_COMPARE_VENDORS} vendors at a time",
        )

    cache_key = f"compare|{','.join(cleaned)}|{house or 'all'}|{_stamp(db)}"
    cached = _cache_get(cache_key)
    if cached is not None:
        return cached

    baseline = _peer_baseline(db, house)
    vendors = []
    for key in cleaned:
        identity = _resolve_vendor(db, key, house)
        metrics = _compare_metrics(db, key, house)
        metrics["vendor_name"] = identity["vendor_name"]
        metrics["vendor_type"] = identity["vendor_type"]
        vendors.append(metrics)

    comparable = [v for v in vendors if v["transaction_count"] > 0]
    notes = [
        "All figures are per-vendor aggregates from the same ledger; percentages are normalised so vendors "
        "of different sizes remain comparable.",
        f"Peer percentiles refer to the {baseline['vendor_count']:,} vendors in the "
        f"{baseline['scope']} scope.",
    ]
    if any(not v["linked_projects"] for v in vendors):
        notes.append(
            "At least one vendor has no exact project linkage, so its completion figures are blank rather "
            "than zero — an absent link is not evidence of non-completion."
        )
    if len(comparable) < len(vendors):
        notes.append("Some selected vendors have no transactions in this scope and are excluded from comparisons.")

    result = {
        "house_scope": house or "All houses",
        "vendor_count": len(vendors),
        "vendors": vendors,
        "metrics": [
            "total_expenditure", "transaction_count", "average_transaction", "largest_transaction_share",
            "works", "mp_count", "constituency_count", "state_count", "top_mp_share",
            "in_progress_share", "repeated_amount_share", "burst_ratio", "linked_projects",
            "risk_score",
        ],
        "peer_baseline": _public_baseline(baseline),
        "notes": notes,
        "method": (
            "Like-for-like comparison uses the same aggregation for every vendor. Percentages, counts and "
            "percentile ranks are shown instead of raw ratios wherever the underlying coverage differs. "
            + METHOD_NOTE
        ),
        "disclaimer": ANOMALY_DISCLAIMER,
    }
    _cache_set(cache_key, result, ttl=180)
    return result


