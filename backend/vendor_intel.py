INTENT_PATTERNS = (
    ("why_flagged", r"why|flag|risk|suspicious|reason|explain|score"),
    ("top_works", r"project|work|contract|contribut|biggest|largest|top|expenditure"),
    ("mps", r"\bmp\b|mps|member|parliament|who (paid|funded)|constituenc"),
    ("patterns", r"pattern|unusual|anomal|irregular|repeat|frequen|burst|concentrat"),
    ("compare", r"compar|similar|peer|benchmark|versus|\bvs\b"),
    ("records", r"record|audit|examin|inspect|evidence|check|verify"),
)


def _intent_for(question: str) -> str:
    text = (question or "").lower()
    for name, pattern in INTENT_PATTERNS:
        if re.search(pattern, text):
            return name
    return "overview"


def _fmt_money(value: float) -> str:
    return f"₹{float(value or 0):,.0f}"


def _similar_by_scale(
    db: Session, key: str, total: float, house: Optional[str]
) -> List[Dict[str, Any]]:
    """Vendors of comparable recorded size that also share at least one state.

    Used for "compare with similar vendors" — a scale/geography peer set, not
    an identity match.
    """
    if total <= 0:
        return []
    frag, params = _scope(house)
    # Narrow to the vendor's own states FIRST (indexed filter on the raw
    # column) so the grouping never scans the whole ledger — joining on
    # normkey(state) across 108k rows costs minutes.
    states = [row[0] for row in db.execute(text(f"""
        SELECT DISTINCT trim(state) AS state
        FROM expenditures
        WHERE normkey(vendor) = :k AND {frag}
          AND state IS NOT NULL AND trim(state) <> ''
        LIMIT 5
    """), {**params, "k": key}).fetchall()]
    if not states:
        return []
    placeholders = ", ".join(f":s{i}" for i in range(len(states)))
    state_params = {f"s{i}": value for i, value in enumerate(states)}
    rows = db.execute(text(f"""
        SELECT normkey(vendor) AS k, MAX(vendor) AS name,
               ROUND(SUM(expenditure_amount), 2) AS total,
               COUNT(*) AS tx,
               COUNT(DISTINCT normkey(state)) AS states
        FROM expenditures
        WHERE vendor IS NOT NULL AND trim(vendor) <> ''
          AND state IN ({placeholders})
          AND normkey(vendor) <> :k
          {"AND house = :house" if house in HOUSE_VALUES else ""}
        GROUP BY k
        HAVING total BETWEEN :lo AND :hi
        ORDER BY ABS(total - :total) ASC
        LIMIT 5
    """), {
        **state_params,
        **params,
        "k": key,
        "lo": total * 0.6,
        "hi": total * 1.6,
        "total": total,
    }).mappings().all()
    return [{
        "vendor_key": r["k"],
        "vendor_name": r["name"],
        "total_expenditure": float(r["total"] or 0),
        "transactions": int(r["tx"] or 0),
        "shared_states": int(r["states"] or 0),
    } for r in rows]


def vendor_assistant(
    db: Session,
    vendor_key: str,
    question: str,
    house: Optional[str] = None,
) -> Dict[str, Any]:
    """Answer a vendor question using stored records only.

    There is no generative model in this codebase, and this keeps it that
    way: the question is routed to a deterministic analysis of real rows, and
    every figure in the answer is copied from a query result. When the data
    cannot answer a question, the reply says so instead of guessing.
    """
    identity = _resolve_vendor(db, vendor_key, house)
    key = identity["vendor_key"]
    intent = _intent_for(question)

    risk = vendor_risk(db, key, house)
    perf = vendor_performance(db, key, house)
    data = _vendor_risk_inputs(db, key, house)

    bullets: List[str] = []
    evidence: List[Dict[str, Any]] = []
    sources: List[str] = ["expenditures", "projects", "project_rec_info", "risk_scores"]
    answer = ""

    if intent == "why_flagged":
        answer = (
            f"{identity['vendor_name']} scores {risk['risk_score']}/100 on the recorded-data indicators "
            f"({risk['risk_category']} · {risk['confidence']} confidence). "
            f"{risk['category_detail']}"
        )
        if risk["top_signals"]:
            bullets = [
                f"{s['label']} ({s['severity_label']}): {s['value']}"
                for s in risk["top_signals"]
            ]
        else:
            bullets = [
                "No indicator currently exceeds the peer-based threshold, so nothing is flagged. "
                "That is not a clean bill of health — it only means the recorded data shows no strong anomaly."
            ]
        for indicator in risk["indicators"]:
            if indicator["evidence"] and indicator["severity"] >= 0.33:
                evidence.extend(indicator["evidence"][:2])

    elif intent == "top_works":
        works = perf["works"][:5]
        answer = (
            f"The largest recorded works for {identity['vendor_name']} are listed below "
            f"({len(perf['works'])} of {perf['totals']['work_count']} distinct works, "
            f"{_fmt_money(perf['totals']['total_expenditure'])} total expenditure)."
        )
        bullets = [
            f"{w['amount'] and _fmt_money(w['amount'])} — {w['work_description']} "
            f"({w['transactions']} payments, {w['share']}% of this vendor's expenditure, {w['constituency']})"
            for w in works
        ]
        evidence = [{
            "type": "work",
            "work_description": w["work_description"],
            "constituency": w["constituency"],
            "state": w["state"],
            "amount": w["amount"],
            "transactions": w["transactions"],
        } for w in works]
        if data["largest"]:
            bullets.append(
                f"Largest single payment: {_fmt_money(data['largest'][0]['amount'])} on "
                f"{data['largest'][0]['date'] or 'an unrecorded date'}."
            )

    elif intent == "mps":
        mps = perf["mp_distribution"][:8]
        answer = (
            f"{identity['vendor_name']} is linked to {perf['totals']['mp_count']} MP payer(s) across "
            f"{perf['totals']['constituency_count']} constituencies in {perf['totals']['state_count']} states."
        )
        bullets = [
            f"{m['label']}: {_fmt_money(m['amount'])} over {m['transactions']} payments ({m['share']}%)"
            for m in mps
        ]
        evidence = [{
            "type": "mp",
            "mp_name": m["label"],
            "amount": m["amount"],
            "transactions": m["transactions"],
        } for m in mps[:5]]

    elif intent == "patterns":
        flagged = [i for i in risk["indicators"] if i["assessable"] and i["severity"] >= 0.33]
        answer = (
            f"{len(flagged)} of {len(risk['indicators'])} indicators are above their peer threshold for "
            f"{identity['vendor_name']}. The values below are measured against all "
            f"{risk['peer_baseline']['vendor_count']:,} vendors in the {risk['house_scope']} scope."
        )
        bullets = [
            f"{i['label']}: {i['value']} — {i['peer_context']}" for i in flagged
        ] or ["No indicator currently exceeds its peer threshold in the recorded data."]
        if data["repeat_rows"]:
            top_repeat = data["repeat_rows"][0]
            bullets.append(
                f"Most repeated amount: {_fmt_money(top_repeat['amount'])} appears "
                f"{int(top_repeat['n'])} times."
            )
        if data["burst_ratio"] >= 1.5:
            bullets.append(
                f"Busiest 30-day window holds {data['max_30']} payments "
                f"({data['burst_ratio']:.1f}× the vendor's monthly average)."
            )
        evidence = data["largest"][:3]

    elif intent == "compare":
        peers = _similar_by_scale(db, key, data["total"], house)
        own_avg = (data["total"] / data["tx"]) if data["tx"] else 0.0
        answer = (
            f"{identity['vendor_name']} records {_fmt_money(data['total'])} across {data['tx']} payments "
            f"(average {_fmt_money(own_avg)}), placing it at the "
            f"{perf['totals']['expenditure_percentile']}th percentile of vendor expenditure. "
            "Comparable vendors sharing at least one state are listed below."
        )
        bullets = [
            f"{p['vendor_name']}: {_fmt_money(p['total_expenditure'])} over {p['transactions']} payments"
            for p in peers
        ]
        if peers:
            peer_avg = sum(p["total_expenditure"] / max(1, p["transactions"]) for p in peers) / len(peers)
            bullets.append(
                f"Average payment size: own {_fmt_money(own_avg)} vs comparable peers {_fmt_money(peer_avg)}."
            )
        else:
            bullets.append("No comparable peer vendor was found for this scale and geography.")
        evidence = peers
        sources.append("vendor scale/state peer join")

    elif intent == "records":
        answer = (
            "The records below are the ones an auditor would start with: the largest payments, "
            "the amounts repeated most often, any linked high-risk project, and payments still in progress."
        )
        bullets = [
            f"{_fmt_money(t['amount'])} — {t['title']} ({t['date'] or 'date not recorded'}, "
            f"{t['mp_name'] or 'MP not recorded'}, {t['status'] or 'status not recorded'})"
            for t in data["largest"][:5]
        ]
        for repeat in data["repeat_rows"][:3]:
            bullets.append(
                f"Amount {_fmt_money(repeat['amount'])} recorded {int(repeat['n'])} times."
            )
        high_risk = [p for p in risk["evidence"]["linked_projects"] if p["risk_level"] == "High"]
        for project in high_risk[:3]:
            bullets.append(
                f"Linked project #{project['id']} {project['project_name']} — risk {project['risk_score']} "
                f"({project['risk_level']}), completion {project['completion_percentage']}%."
            )
        evidence = data["largest"][:5]

    else:
        answer = (
            f"{identity['vendor_name']} ({identity['vendor_type']}) has {perf['totals']['transaction_count']} "
            f"recorded payments totalling {_fmt_money(perf['totals']['total_expenditure'])}, "
            f"{perf['totals']['work_count']} distinct works, {perf['totals']['mp_count']} MP payer(s) and "
            f"{perf['totals']['constituency_count']} constituencies. Recorded activity runs from "
            f"{perf['totals']['first_activity'] or 'an unrecorded date'} to "
            f"{perf['totals']['last_activity'] or 'an unrecorded date'}."
        )
        bullets = [
            "Ask about: why this vendor is flagged, which works dominate its expenditure, which MPs are "
            "associated with it, what unusual patterns exist, how it compares with similar vendors, or "
            "which records an auditor should examine.",
        ]

    return {
        "vendor_key": key,
        "vendor_name": identity["vendor_name"],
        "question": question,
        "intent": intent,
        "answer": answer,
        "bullets": [b for b in bullets if b],
        "evidence": evidence,
        "sources": sources,
        "data_scope": house or "All houses",
        "snapshot": {
            "transaction_count": perf["totals"]["transaction_count"],
            "total_expenditure": perf["totals"]["total_expenditure"],
            "work_count": perf["totals"]["work_count"],
            "mp_count": perf["totals"]["mp_count"],
            "risk_score": risk["risk_score"],
            "risk_category": risk["risk_category"],
        },
        "method": (
            "Deterministic analyst: the question is matched to one of a fixed set of analysis routines and "
            "every figure is copied from the queries listed under sources. No language model generates, "
            "estimates or fills in numbers."
        ),
        "disclaimer": ANOMALY_DISCLAIMER,
    }


