"""
Vendor Performance & Audit Intelligence
=======================================

Aggregation and analysis layer behind the existing Vendor Intelligence and
Vendor Network pages. This module adds *derived* intelligence only — it never
writes to, rewrites or renames a single vendor record.

Data reality (checked against the live dataset):
  * `expenditures` is the only table with a vendor column (108k rows, ~28k
    distinct vendors). It has no project_id, so vendor → work linkage uses the
    normalized work key (work_description + constituency + state), exactly the
    same conservative rule the existing vendor endpoints use.
  * `projects` / `recommended_works` / `completed_works` carry category,
    completion and risk data, but only a small slice of vendor work keys match
    them exactly (≈1.1k vendors have a project link, ≈0.4k a completion link).
    Every payload therefore reports linkage *coverage*, and the UI never
    presents completion/category data as if it covered the whole vendor.

Design rules baked into the code:
  * Anomaly != misconduct. Indicators carry method + explanation + evidence
    rows, and the composite score is labelled as an audit lead.
  * No vendor merging on similar names. `relationships` returns possible name
    variants separately, flagged "not merged".
  * Peer baselines are computed from the whole vendor population (per house
    scope) and cached in-process; per-vendor endpoints stay single-vendor SQL.
  * Nothing is generated by an LLM: the assistant is a deterministic router
    over real rows (same philosophy as assistant.py), so amounts, MPs and
    transactions always come from the database.
"""

