def _similar_vendors(db: Session, key: str, house: Optional[str]) -> List[Dict[str, Any]]:
    """Possible name variants of the same trading name.

    Returned SEPARATELY and never merged into the vendor's figures: shared
    tokens are a data-quality hint for manual review, not an identity match.
    """
    first = key.split(" ")[0]
    if not first:
        return []
    frag, params = _scope(house)
    rows = db.execute(text(f"""
        SELECT normkey(vendor) AS k, MAX(vendor) AS name,
               COUNT(*) AS tx, ROUND(COALESCE(SUM(expenditure_amount), 0), 2) AS total,
               COUNT(DISTINCT normkey(state)) AS states
        FROM expenditures
        WHERE {frag} AND normkey(vendor) <> :k
          AND normkey(vendor) >= :lo AND normkey(vendor) <= :hi
        GROUP BY k
        ORDER BY total DESC
        LIMIT 40
    """), {**params, "k": key, "lo": first, "hi": first + "\x7f"}).mappings().all()

    key_tokens = set(key.split())
    matches = []
    for row in rows:
        other_tokens = set(str(row["k"]).split())
        if not other_tokens:
            continue
        overlap = len(key_tokens & other_tokens) / max(1, min(len(key_tokens), len(other_tokens)))
        if overlap < 0.4:
            continue
        matches.append({
            "vendor_key": row["k"],
            "vendor_name": row["name"],
            "transactions": int(row["tx"] or 0),
            "total_expenditure": float(row["total"] or 0),
            "states": int(row["states"] or 0),
            "token_overlap": round(overlap, 2),
            "relation": "possible name variant — not merged",
            "reason": (
                "Shares name tokens with this vendor but has a different normalized key. "
                "Vendors are never merged on name similarity alone."
            ),
        })
    matches.sort(key=lambda m: m["total_expenditure"], reverse=True)
    return matches[:8]


