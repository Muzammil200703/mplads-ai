def _month_span(first_month: Optional[str], last_month: Optional[str]) -> int:
    """Inclusive number of calendar months between two YYYY-MM stamps.

    Used as the activity window for the frequency flags. A span is cheaper and
    more stable than counting distinct active months, and it cannot make a
    burst of payments look slower than it was.
    """
    try:
        fy, fm = int(str(first_month)[:4]), int(str(first_month)[5:7])
        ly, lm = int(str(last_month)[:4]), int(str(last_month)[5:7])
        return max(1, (ly - fy) * 12 + (lm - fm) + 1)
    except Exception:
        return 1


def _scan_candidates(db: Session, house: Optional[str], min_tx: int) -> List[Dict[str, Any]]:
    frag, params = _scope(house)
    rows = db.execute(text(f"""
        WITH vm AS (
            SELECT normkey(vendor) AS k, normkey(mp_name) AS m,
                   SUM(expenditure_amount) AS amt
            FROM expenditures
            WHERE {frag}
            GROUP BY k, m
        ),
        mpstat AS (SELECT k, MAX(amt) AS top_amt, SUM(amt) AS tot FROM vm GROUP BY k),
        pv AS (
            SELECT normkey(vendor) AS k, MAX(vendor) AS name,
                   COUNT(*) AS tx,
                   ROUND(COALESCE(SUM(expenditure_amount), 0), 2) AS total,
                   COALESCE(MAX(expenditure_amount), 0) AS max_tx,
                   COUNT(DISTINCT normkey(mp_name)) AS mps,
                   COUNT(DISTINCT normkey(constituency)) AS cons,
                   COUNT(DISTINCT normkey(state)) AS sts,
                   MIN(substr(expenditure_date, 1, 7)) AS first_month,
                   MAX(substr(expenditure_date, 1, 7)) AS last_month,
                   COUNT(DISTINCT expenditure_amount) * 1.0 / COUNT(*) AS variety,
                   SUM(CASE WHEN payment_status = 'Payment In-Progress' THEN 1 ELSE 0 END) AS inprog,
                   SUM(CASE WHEN work_description IS NULL OR trim(work_description) = ''
                              OR constituency IS NULL OR trim(constituency) = ''
                              OR state IS NULL OR trim(state) = ''
                            THEN 1 ELSE 0 END) AS missing
            FROM expenditures
            WHERE {frag}
            GROUP BY k
        )
        SELECT pv.k, pv.name, pv.tx, pv.total, pv.max_tx, pv.mps, pv.cons, pv.sts,
               pv.first_month, pv.last_month,
               pv.variety, pv.inprog, pv.missing,
               CASE WHEN mpstat.tot > 0 THEN mpstat.top_amt * 1.0 / mpstat.tot ELSE 0 END AS top_mp_share
        FROM pv JOIN mpstat ON mpstat.k = pv.k
        WHERE pv.tx >= :min_tx
        ORDER BY pv.tx DESC
        LIMIT 6000
    """), {**params, "min_tx": min_tx}).mappings().all()

    out = []
    for row in rows:
        tx = int(row["tx"] or 0)
        total = float(row["total"] or 0)
        months = _month_span(row["first_month"], row["last_month"])
        out.append({
            "vendor_key": row["k"],
            "vendor_name": row["name"],
            "transactions": tx,
            "total_expenditure": total,
            "max_tx_share": (float(row["max_tx"] or 0) / total) if total else 0.0,
            "mp_count": int(row["mps"] or 0),
            "constituency_count": int(row["cons"] or 0),
            "state_count": int(row["sts"] or 0),
            "active_months": months,
            "variety": float(row["variety"] or 0),
            "in_progress_rate": (int(row["inprog"] or 0) / tx) if tx else 0.0,
            "missing_rate": (int(row["missing"] or 0) / tx) if tx else 0.0,
            "top_mp_share": float(row["top_mp_share"] or 0),
            "tx_per_month": float(tx) / months,
        })
    return out


def behaviour_scan(
    db: Session,
    house: Optional[str] = None,
    flag: Optional[str] = None,
    skip: int = 0,
    limit: int = 20,
    min_transactions: int = MIN_SCAN_TRANSACTIONS,
) -> Dict[str, Any]:
    """Dataset-wide behaviour screening.

    Every vendor with at least `min_transactions` payments is characterised
    against population baselines; the output is a ranked list of audit leads.
    Vendors below the threshold are not scored at all (stated in the UI)
    because a handful of payments cannot be characterised statistically.
    """
    cache_key = f"scan|{house or 'all'}|{_stamp(db)}|{min_transactions}"
    cached = _cache_get(cache_key)
    if cached is not None:
        scan = cached
    else:
        baseline = _peer_baseline(db, house)
        candidates = _scan_candidates(db, house, min_transactions)
        p99 = baseline["expenditure"]["p99"]

        # Thresholds are derived from the SCREENED population (vendors large
        # enough to characterise), not from all 27k vendors — the population
        # median is dominated by one-payment vendors and would flag almost
        # everyone. This is the peer comparison the screen is about.
        def _cut(values: List[float], q: float) -> float:
            return _percentile(sorted(values), q) if values else 0.0

        variety_cut = _cut([c["variety"] for c in candidates], 0.25)
        large_tx_cut = max(0.5, _cut([c["max_tx_share"] for c in candidates], 0.90))
        velocity_cut = max(6.0, _cut([c["tx_per_month"] for c in candidates], 0.90))
        spend_cut = _cut([c["total_expenditure"] for c in candidates], 0.90)
        multi_mp_shares = [c["top_mp_share"] for c in candidates if c["mp_count"] >= 2]
        top_mp_cut = max(0.97, _cut(multi_mp_shares, 0.95))
        pending_cut = max(0.20, baseline["in_progress_rate"] / 100.0 * 3)

        for c in candidates:
            flags_list = []
            if c["mp_count"] >= 2 and c["top_mp_share"] >= top_mp_cut:
                flags_list.append("concentrated_expenditure")
            if c["mp_count"] == 1 and c["total_expenditure"] >= spend_cut and c["transactions"] >= 20:
                flags_list.append("single_mp_funding")
            if c["constituency_count"] >= 3:
                flags_list.append("multi_constituency")
            if c["tx_per_month"] >= velocity_cut and c["active_months"] <= 6:
                flags_list.append("burst_activity")
            if c["variety"] <= variety_cut and c["transactions"] >= 10:
                flags_list.append("repeated_amounts")
            if c["tx_per_month"] >= velocity_cut * 1.5:
                flags_list.append("high_velocity")
            if c["in_progress_rate"] >= pending_cut:
                flags_list.append("pending_payments")
            if c["max_tx_share"] >= large_tx_cut:
                flags_list.append("large_transactions")
            if c["state_count"] >= 3:
                flags_list.append("multi_state")

            severity = (
                0.30 * (1.0 if "concentrated_expenditure" in flags_list else 0.0)
                + 0.18 * (1.0 if "burst_activity" in flags_list else 0.0)
                + 0.16 * (1.0 if "repeated_amounts" in flags_list else 0.0)
                + 0.14 * (1.0 if "large_transactions" in flags_list else 0.0)
                + 0.12 * (1.0 if "pending_payments" in flags_list else 0.0)
                + 0.10 * (1.0 if "single_mp_funding" in flags_list else 0.0)
                + 0.05 * (1.0 if "high_velocity" in flags_list else 0.0)
            )
            c["flags"] = flags_list
            c["flag_labels"] = [SCAN_FLAGS[f] for f in flags_list]
            c["severity"] = round(min(1.0, severity), 3)
            c["top_percentile"] = c["total_expenditure"] >= p99
            c["tx_per_month"] = round(c["tx_per_month"], 2)

        candidates.sort(
            key=lambda c: (c["severity"], c["total_expenditure"]),
            reverse=True,
        )
        flag_counts: Dict[str, int] = {}
        for c in candidates:
            for f in c["flags"]:
                flag_counts[f] = flag_counts.get(f, 0) + 1
        scan = {
            "evaluated_vendors": len(candidates),
            "flagged_vendors": sum(1 for c in candidates if c["flags"]),
            "flag_counts": flag_counts,
            "thresholds": {
                "min_transactions": min_transactions,
                "amount_variety_below": round(variety_cut, 3),
                "largest_payment_share_at_or_above": round(large_tx_cut, 3),
                "top_mp_share_at_or_above": round(top_mp_cut, 3),
                "single_mp_min_transactions": 20,
                "single_mp_spend_at_or_above": round(spend_cut, 2),
                "payments_per_month_at_or_above": round(velocity_cut, 2),
                "pending_share_at_or_above": round(pending_cut, 3),
                "multi_constituency_min": 3,
                "multi_state_min": 3,
                "top_1pct_expenditure": round(p99, 2),
                "basis": "derived from the screened vendor population (vendors above the transaction minimum)",
            },
            "items": candidates[:300],
            "capped": sum(1 for c in candidates if c["flags"]) > 300,
        }
        _cache_set(cache_key, scan, ttl=300)

    items = scan["items"]
    if flag:
        items = [c for c in items if flag in c["flags"]]
    window = items[skip: skip + limit]
    return {
        "house_scope": house or "All houses",
        "flag_catalog": [{"key": k, "label": v} for k, v in SCAN_FLAGS.items()],
        "selected_flag": flag,
        "stats": {
            "evaluated_vendors": scan["evaluated_vendors"],
            "flagged_vendors": scan["flagged_vendors"],
            "flag_counts": scan["flag_counts"],
            "thresholds": scan["thresholds"],
        },
        "total": len(items),
        "capped": bool(scan.get("capped")),
        "skip": skip,
        "limit": limit,
        "items": [{
            "vendor_key": c["vendor_key"],
            "vendor_name": c["vendor_name"],
            "transactions": c["transactions"],
            "total_expenditure": round(c["total_expenditure"], 2),
            "mp_count": c["mp_count"],
            "constituency_count": c["constituency_count"],
            "state_count": c["state_count"],
            "active_months": c["active_months"],
            "top_mp_share": round(c["top_mp_share"] * 100, 1),
            "in_progress_share": round(c["in_progress_rate"] * 100, 1),
            "payments_per_month": c["tx_per_month"],
            "flags": c["flags"],
            "flag_labels": c["flag_labels"],
            "severity": c["severity"],
            "top_percentile": c["top_percentile"],
        } for c in window],
        "method": (
            "Vendors with at least "
            f"{min_transactions} recorded payments are characterised against population baselines "
            "(same house scope); smaller vendors are excluded because the patterns cannot be measured "
            "reliably. Every flag is a statistical lead for examination — " + ANOMALY_DISCLAIMER
        ),
        "disclaimer": ANOMALY_DISCLAIMER,
    }

