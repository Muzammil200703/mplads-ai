# ═══════════════════════════════════════════════════════════════════
# Small in-process cache (bounded, TTL, cleared implicitly by the stamp
# check on the peer baseline — dataset changes invalidate the baseline).
# ═══════════════════════════════════════════════════════════════════

_CACHE: Dict[str, Tuple[float, Any]] = {}
_CACHE_LOCK = threading.Lock()
_CACHE_MAX_ENTRIES = 256


def _cache_get(key: str) -> Any:
    with _CACHE_LOCK:
        entry = _CACHE.get(key)
        if not entry:
            return None
        expires_at, value = entry
        if expires_at < time.time():
            _CACHE.pop(key, None)
            return None
        return value


def _cache_set(key: str, value: Any, ttl: int = 300) -> None:
    with _CACHE_LOCK:
        if len(_CACHE) >= _CACHE_MAX_ENTRIES:
            # Drop the oldest half rather than growing without bound.
            for stale in sorted(_CACHE, key=lambda k: _CACHE[k][0])[: _CACHE_MAX_ENTRIES // 2]:
                _CACHE.pop(stale, None)
        _CACHE[key] = (time.time() + ttl, value)


def clear_vendor_intel_cache() -> None:
    """Called by the shared data-sync path so analysis never serves stale
    rows after an import."""
    with _CACHE_LOCK:
        _CACHE.clear()


