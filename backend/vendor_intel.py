def _scope(house: Optional[str]) -> Tuple[str, Dict[str, Any]]:
    """WHERE fragment shared by every query: vendor-linked rows only, plus an
    optional house filter. NULL/unknown house rows are excluded when a
    specific house is requested (never silently attributed to a house)."""
    frag = "vendor IS NOT NULL AND trim(vendor) <> ''"
    params: Dict[str, Any] = {}
    if house in HOUSE_VALUES:
        frag += " AND house = :house"
        params["house"] = house
    return frag, params


def _stamp(db: Session) -> str:
    return str(db.execute(text(
        "SELECT COUNT(*) || ':' || COALESCE(MAX(id), 0) FROM expenditures"
    )).scalar() or "0:0")


def _vendor_type(name: str) -> Tuple[str, str]:
    """Reuse main.py's classifier when available (it is, at request time);
    fall back to an identical local rule if the import ever fails."""
    try:
        from main import _vendor_type as main_vendor_type  # local import: avoids circularity
        return main_vendor_type(name)
    except Exception:
        pass
    raw = str(name or "").strip()
    lower = raw.lower()
    if not raw:
        return "Unknown", "low"
    if re.search(r"\b(panchayat|municipal|municipality|nagarpalika|local body|gram sabha)\b", lower):
        return "Panchayat/Local Body", "medium"
    if re.search(r"\b(government|govt|department|ministry|pwd|rural development|zila parishad)\b", lower):
        return "Government Department", "medium"
    if re.search(r"\b(mr|mrs|ms|shri|smt|dr)\.?\s+", lower) and not re.search(r"\b(ltd|llp|pvt|company|enterprises?)\b", lower):
        return "Individual", "low"
    if re.search(r"\b(contractor|supplier|vendor|works|construction|infrastructure|traders?|agency)\b", lower):
        return "Supplier/Contractor", "medium"
    if re.search(r"\b(ltd|limited|llp|pvt|private|company|industries|enterprise|enterprises|corp|corporation)\b", lower):
        return "Company/Business", "medium"
    return "Other/Unknown", "low"


def _percentile(sorted_values: List[float], q: float) -> float:
    if not sorted_values:
        return 0.0
    idx = int(round(q * (len(sorted_values) - 1)))
    idx = max(0, min(len(sorted_values) - 1, idx))
    return sorted_values[idx]


def _quantiles(values: List[float]) -> Dict[str, float]:
    ordered = sorted(values)
    return {
        "p50": round(_percentile(ordered, 0.50), 4),
        "p75": round(_percentile(ordered, 0.75), 4),
        "p90": round(_percentile(ordered, 0.90), 4),
        "p95": round(_percentile(ordered, 0.95), 4),
        "p99": round(_percentile(ordered, 0.99), 4),
        "max": round(ordered[-1], 4) if ordered else 0.0,
    }


def _rank_percentile(ordered: List[float], value: float) -> float:
    """Share of the peer population at or below `value` (0..100)."""
    if not ordered:
        return 0.0
    lo, hi = 0, len(ordered)
    while lo < hi:
        mid = (lo + hi) // 2
        if ordered[mid] <= value:
            lo = mid + 1
        else:
            hi = mid
    return round(lo * 100.0 / len(ordered), 1)


_BASELINE_LOCKS: Dict[str, threading.Lock] = {}
_BASELINE_LOCKS_GUARD = threading.Lock()


def _baseline_lock(name: str) -> threading.Lock:
    with _BASELINE_LOCKS_GUARD:
        return _BASELINE_LOCKS.setdefault(name, threading.Lock())


def _peer_baseline(db: Session, house: Optional[str]) -> Dict[str, Any]:
    """Population baselines used for peer comparison.

    One grouped scan over `expenditures`, keeping only the five scalar
    metrics the indicators actually need (one compact tuple per vendor,
    released immediately; the expensive DISTINCT-per-vendor counts are
    deliberately not part of the baseline). Cached per house scope, keyed by
    the dataset stamp, with single-flight so concurrent dashboards cause one
    build rather than N.
    """
    stamp = _stamp(db)
    cache_key = f"baseline|{house or 'all'}|{stamp}"
    cached = _cache_get(cache_key)
    if cached is not None:
        return cached

    with _baseline_lock(cache_key):
        cached = _cache_get(cache_key)
        if cached is not None:
            return cached

        frag, params = _scope(house)
        rows = db.execute(text(f"""
            SELECT COUNT(*) AS tx,
                   COALESCE(SUM(expenditure_amount), 0) AS total,
                   COALESCE(MAX(expenditure_amount), 0) AS max_tx,
                   COUNT(DISTINCT expenditure_amount) * 1.0 / COUNT(*) AS variety,
                   SUM(CASE WHEN payment_status = 'Payment In-Progress' THEN 1 ELSE 0 END) AS inprog
            FROM expenditures
            WHERE {frag}
            GROUP BY normkey(vendor)
        """), params).all()

        totals: List[float] = []
        tx_counts: List[float] = []
        avg_sizes: List[float] = []
        max_shares: List[float] = []
        varieties: List[float] = []
        in_progress_total = 0
        transaction_total = 0
        for row in rows:
            tx = int(row.tx or 0)
            total = float(row.total or 0)
            totals.append(total)
            tx_counts.append(float(tx))
            avg_sizes.append(total / tx if tx else 0.0)
            max_shares.append(float(row.max_tx or 0) / total if total else 0.0)
            varieties.append(float(row.variety or 0))
            in_progress_total += int(row.inprog or 0)
            transaction_total += tx
        vendor_count = len(rows)
        del rows

        baseline = {
            "scope": house or "All houses",
            "vendor_count": vendor_count,
            "transaction_count": transaction_total,
            "total_expenditure": round(sum(totals), 2),
            "in_progress_rate": round(
                (in_progress_total / transaction_total * 100) if transaction_total else 0.0, 2
            ),
            "expenditure": _quantiles(totals),
            "transactions": _quantiles(tx_counts),
            "average_transaction": _quantiles(avg_sizes),
            "largest_transaction_share": _quantiles(max_shares),
            "amount_variety": _quantiles(varieties),
            # Sorted value lists back the exact percentile ranks shown in the
            # UI; they stay inside the cached baseline (never returned raw).
            "_totals_sorted": sorted(totals),
            "_tx_sorted": sorted(tx_counts),
            "_avg_sorted": sorted(avg_sizes),
        }
        _cache_set(cache_key, baseline, ttl=900)
        return baseline


def _multi_mp_baseline(db: Session, house: Optional[str]) -> Dict[str, Any]:
    """Top-MP concentration baseline, restricted to vendors paid by more than
    one MP (the population where that share is meaningful).

    Separate from `_peer_baseline` because the two-level grouping is the most
    expensive scan in this module; it is only built when a vendor (or a
    comparison) actually records several MPs.
    """
    stamp = _stamp(db)
    cache_key = f"multi_mp|{house or 'all'}|{stamp}"
    cached = _cache_get(cache_key)
    if cached is not None:
        return cached

    with _baseline_lock(cache_key):
        cached = _cache_get(cache_key)
        if cached is not None:
            return cached

        frag, params = _scope(house)
        rows = db.execute(text(f"""
            WITH vm AS (
                SELECT normkey(vendor) AS k, normkey(mp_name) AS m,
                       SUM(expenditure_amount) AS amt
                FROM expenditures
                WHERE {frag}
                GROUP BY k, m
            ),
            tot AS (SELECT k, SUM(amt) AS t, COUNT(*) AS n FROM vm GROUP BY k)
            SELECT mx.top * 1.0 / tot.t AS share
            FROM (SELECT k, MAX(amt) AS top FROM vm GROUP BY k) mx
            JOIN tot ON tot.k = mx.k
            WHERE tot.n >= 2
        """), params).all()
        shares = sorted(float(r.share or 0) for r in rows)
        del rows
        result = {
            "vendor_count": len(shares),
            "top_mp_share": _quantiles(shares),
        }
        _cache_set(cache_key, result, ttl=900)
        return result


def _public_baseline(baseline: Dict[str, Any]) -> Dict[str, Any]:
    """Strip the internal sorted lists before sending a baseline to the UI."""
    return {k: v for k, v in baseline.items() if not k.startswith("_")}


def _resolve_vendor(db: Session, vendor_key: str, house: Optional[str]) -> Dict[str, Any]:
    key = str(vendor_key or "").strip().lower()
    if not key:
        raise HTTPException(status_code=404, detail="Vendor not found in the current MPLADS dataset")
    frag, params = _scope(house)
    row = db.execute(text(f"""
        SELECT MAX(vendor) AS vendor_name,
               COUNT(*) AS tx,
               ROUND(COALESCE(SUM(expenditure_amount), 0), 2) AS total
        FROM expenditures
        WHERE normkey(vendor) = :k AND {frag}
    """), {**params, "k": key}).mappings().first()
    if not row or not row["vendor_name"]:
        raise HTTPException(
            status_code=404,
            detail=(
                "Vendor not found in the current MPLADS dataset"
                + (" for the selected house filter" if house else "")
            ),
        )
    name = str(row["vendor_name"]).strip()
    vtype, vconf = _vendor_type(name)
    return {
        "vendor_key": key,
        "vendor_name": name,
        "vendor_type": vtype,
        "type_confidence": vconf,
        "transaction_count": int(row["tx"] or 0),
        "total_expenditure": float(row["total"] or 0),
    }


def _linked_projects(db: Session, key: str, house: Optional[str]) -> List[Dict[str, Any]]:
    """Projects linked to this vendor by the exact normalized work key.

    Sparse by nature (the ledger has no project id); callers must present the
    result as a subset, never as the vendor's full portfolio."""
    frag, params = _scope(house)
    rows = db.execute(text(f"""
        SELECT p.id, p.project_name, p.state, p.district, p.constituency,
               p.project_type, p.sanctioned_amount, p.completion_percentage,
               p.status, p.house,
               pri.linked_expenditure, pri.linked_tx_count,
               rs.risk_score, rs.risk_level
        FROM (
            SELECT DISTINCT normkey(work_description) AS wk,
                            normkey(constituency) AS ck,
                            normkey(state) AS sk
            FROM expenditures
            WHERE normkey(vendor) = :k AND {frag}
              AND work_description IS NOT NULL AND trim(work_description) <> ''
              AND constituency IS NOT NULL AND trim(constituency) <> ''
              AND state IS NOT NULL AND trim(state) <> ''
        ) e
        JOIN projects p
          ON normkey(p.project_name) = e.wk
         AND normkey(p.constituency) = e.ck
         AND normkey(p.state) = e.sk
        LEFT JOIN project_rec_info pri ON pri.project_id = p.id
        LEFT JOIN risk_scores rs ON rs.project_id = p.id
    """), {**params, "k": key}).mappings().all()

    projects: List[Dict[str, Any]] = []
    for row in rows:
        completion = float(row["completion_percentage"] or 0)
        if completion >= 100:
            stage = "Completed"
        elif completion <= 0:
            stage = "Not started / no recorded progress"
        else:
            stage = "In progress"
        projects.append({
            "id": row["id"],
            "project_name": row["project_name"],
            "state": row["state"],
            "district": row["district"],
            "constituency": row["constituency"],
            "project_type": row["project_type"],
            "house": row["house"],
            "sanctioned_amount": round(float(row["sanctioned_amount"] or 0), 2),
            "recorded_expenditure": round(float(row["linked_expenditure"] or 0), 2),
            "recorded_transactions": int(row["linked_tx_count"] or 0),
            "completion_percentage": round(completion, 1),
            "stage": stage,
            "status": row["status"],
            "risk_score": int(row["risk_score"] or 0),
            "risk_level": str(row["risk_level"] or "Low").title(),
        })
    return projects


def _works_cte() -> str:
    """Distinct work keys recorded in a vendor's own payment rows."""
    return """
        SELECT DISTINCT normkey(work_description) AS wk,
                        normkey(constituency) AS ck,
                        normkey(state) AS sk
        FROM expenditures
        WHERE normkey(vendor) = :k AND {frag}
          AND work_description IS NOT NULL AND trim(work_description) <> ''
    """


