def vendor_activity(
    db: Session,
    vendor_key: str,
    house: Optional[str] = None,
    skip: int = 0,
    limit: int = 50,
    event_type: str = "all",
) -> Dict[str, Any]:
    """Chronological payment history plus completion milestones where the
    vendor's work keys link to a completed-work row.

    Paginated in SQL (ORDER BY date DESC, id DESC) so a vendor with hundreds
    of payments never loads its full history into the browser.
    """
    identity = _resolve_vendor(db, vendor_key, house)
    key = identity["vendor_key"]
    frag, params = _scope(house)
    scoped = {**params, "k": key}

    cache_key = f"activity|{key}|{house or 'all'}|{skip}|{limit}|{event_type}"
    cached = _cache_get(cache_key)
    if cached is not None:
        return cached

    total = int(db.execute(text(f"""
        SELECT COUNT(*) FROM expenditures WHERE normkey(vendor) = :k AND {frag}
    """), scoped).scalar() or 0)

    events: List[Dict[str, Any]] = []
    if event_type in ("all", "payment"):
        rows = db.execute(text(f"""
            SELECT id, substr(expenditure_date, 1, 10) AS event_date,
                   work_description, mp_name, constituency, state, house,
                   expenditure_amount, payment_status
            FROM expenditures
            WHERE normkey(vendor) = :k AND {frag}
            ORDER BY COALESCE(substr(expenditure_date, 1, 10), '') DESC, id DESC
            LIMIT :lim OFFSET :off
        """), {**scoped, "lim": limit, "off": skip}).mappings().all()
        for row in rows:
            events.append({
                "source": "expenditures",
                "record_id": row["id"],
                "type": "payment",
                "date": row["event_date"],
                "title": row["work_description"] or "(work description not recorded)",
                "mp_name": row["mp_name"],
                "constituency": row["constituency"],
                "state": row["state"],
                "house": row["house"],
                "amount": round(float(row["expenditure_amount"] or 0), 2),
                "status": row["payment_status"],
            })

    milestones = []
    if event_type in ("all", "completion"):
        rows = db.execute(text(f"""
            SELECT cw.id, substr(cw.completed_date, 1, 10) AS event_date,
                   cw.work_description, cw.mp_name, cw.constituency, cw.state,
                   cw.house, cw.final_amount, cw.category, cw.average_rating
            FROM ({_works_cte().format(frag=frag)}) e
            JOIN completed_works cw
              ON normkey(cw.work_description) = e.wk
             AND normkey(cw.constituency) = e.ck
             AND normkey(cw.state) = e.sk
            ORDER BY COALESCE(substr(cw.completed_date, 1, 10), '') DESC, cw.id DESC
            LIMIT 25
        """), scoped).mappings().all()
        for row in rows:
            milestones.append({
                "source": "completed_works",
                "record_id": row["id"],
                "type": "completion",
                "date": row["event_date"],
                "title": row["work_description"] or "(work description not recorded)",
                "mp_name": row["mp_name"],
                "constituency": row["constituency"],
                "state": row["state"],
                "house": row["house"],
                "amount": round(float(row["final_amount"] or 0), 2),
                "status": "Completed",
                "category": row["category"],
                "average_rating": row["average_rating"],
            })

    yearly_rows = db.execute(text(f"""
        SELECT substr(expenditure_date, 1, 4) AS year,
               COUNT(*) AS n,
               ROUND(COALESCE(SUM(expenditure_amount), 0), 2) AS amount
        FROM expenditures
        WHERE normkey(vendor) = :k AND {frag}
          AND expenditure_date IS NOT NULL AND trim(expenditure_date) <> ''
        GROUP BY year
        ORDER BY year
    """), scoped).mappings().all()

    result = {
        "vendor_key": key,
        "vendor_name": identity["vendor_name"],
        "house_scope": house or "All houses",
        "total_events": total,
        "skip": skip,
        "limit": limit,
        "events": events,
        "milestones": milestones,
        "yearly": [{
            "year": row["year"],
            "transactions": int(row["n"] or 0),
            "amount": float(row["amount"] or 0),
        } for row in yearly_rows],
        "notes": [
            "Payment events come from the MPLADS expenditure ledger and use the recorded date only.",
            "Completion milestones appear only where the vendor's work key matches a completed-work row exactly.",
        ],
        "data_source": "Current MPLADS expenditure / completion dataset",
    }
    _cache_set(cache_key, result, ttl=180)
    return result



